#!/usr/bin/env python3
"""Deterministic gates for the brd-to-production workflow. Works for any stack.
Run from the project root. Python 3.8+, standard library only.

  brd_gate.py detect                       guess the stack from files in the project
  brd_gate.py profile-init [--stack X]     create docs/brd-to-production/PROJECT-PROFILE.md from a stack template
  brd_gate.py profile-check                validate the profile's JSON block
  brd_gate.py init <slug> --brd <file>     create the run workspace and state.json, record the base commit
  brd_gate.py status <ws>                  one-screen summary of state and phases
  brd_gate.py brd-hash <ws> [--record]     MATCH (reuse an analysed copy of this BRD) / CHANGED / NEW; --record after analysis
  brd_gate.py context-check <ws> [--record [--full]]
                                           REUSE / INCREMENTAL <files> / FULL <reason> for the project analysis
  brd_gate.py readonly <ws>                fail if anything outside docs/brd-to-production/ changed
  brd_gate.py approve <ws> --mode auto|ask --quote "<user's words>"
  brd_gate.py install-harness <ws>         phase 0: copy the browser/API runner (+ stack harness, if any)
  brd_gate.py phase-start <ws> <N>         record the phase base commit, status implementing
  brd_gate.py scope <ws> <N>               changed files vs the phase's Allowed File Areas and protected paths
  brd_gate.py shards <ws> <N> [--done S1,S2] [--running S3] [--failed S4]
                                           check the phase's Test Shards and print waves; with the options, which shards are READY now
  brd_gate.py shard-merge <ws> <N>         merge shards/<id>/report.md into test-report.md / ui-report.md
  brd_gate.py regression <ws> <N>          run every BRD test suite (+ UI/API flows) into evidence/regression-K
  brd_gate.py evidence <ws> <N>            every PASS/FAIL row points to evidence that confirms it
  brd_gate.py coverage <ws> <N>            every AC of the phase has an evidence-confirmed PASS row
  brd_gate.py bugs <ws> <N>                bugs in phases/phase-N/bugs*.md that are not verified
  brd_gate.py complete <ws> <N>            all of the above, no FAIL, every BLOCKED/NOT RUN accepted by the user
  brd_gate.py accept <ws> <N> <case-id> --quote "<user's words>"
  brd_gate.py fix-round <ws> <N>           count a fix round; exit 1 after 3 rounds (escalate to the user)
  brd_gate.py commit-record <ws> <N>       store HEAD as the phase commit, status committed
  brd_gate.py junit2txt <file.xml>         print a JUnit XML file as "PASS <name>" lines (readable evidence)
  brd_gate.py log <ws> <kind> <message>    append a line to decisions.md

Exit code 0 = gate passed, 1 = gate failed, 2 = usage or state error.
"""
import datetime
import fnmatch
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = "docs/brd-to-production"
PROFILE = os.path.join(ROOT, "PROJECT-PROFILE.md")
SKILL_DIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
STATUSES = ("PASS", "FAIL", "BLOCKED", "NOT RUN")
ALWAYS_ALLOWED = ("tests/brd/*",)
# build and cache noise that is never "a change" (normally gitignored anyway)
NOISE = ("*__pycache__/*", "*.pyc", ".pytest_cache/*", "*/.pytest_cache/*", "tests/brd/ui/node_modules/*",
         ".coverage", "*.egg-info/*", ".phpunit.result.cache", ".phpunit.cache/*", ".DS_Store", "*/.DS_Store")
SECRET_FILES = (".env.brd-test",)
PASS_WORDS = r"(?:PASS|PASSED|OK|✓|✔|√)"
FAIL_WORDS = r"(?:FAIL|FAILED|FAILURE|ERROR|ERRORED|NOT OK|✗|✕|✘|×)"
ID_RE = r"(?:TC|UI|API)-[A-Z0-9]+-[A-Z0-9]+"
AC_RE = r"\bAC-[A-Za-z0-9]+(?:\.[A-Za-z0-9]+)*"
SHARD_AGENTS = ("brd-test-engineer", "brd-ui-tester")
SHARD_RES_RE = r"none|db:read|db:write|server|fixtures:[\w.-]+"
SHARD_HINT_ACS = 3  # phases with more ACs than this are worth sharding
GENERATED = "<!-- generated by brd_gate.py shard-merge: edit shards/<id>/report.md, then re-run shard-merge -->"
# a change to any of these means the project analysis must be redone in full
DEP_FILES = ("composer.json", "composer.lock", "package.json", "package-lock.json", "yarn.lock", "pnpm-lock.yaml",
             "requirements*.txt", "pyproject.toml", "poetry.lock", "uv.lock", "Pipfile", "Pipfile.lock", "setup.py",
             "setup.cfg", "Gemfile", "Gemfile.lock", "go.mod", "go.sum")
SCHEMA_FILES = ("*migrations/*", "*/migration/*", "*/doctype/*/*.json", "*__manifest__.py", "*.sql", "*schema.prisma")
REGRESSION_TIMEOUT = 1800


# ---------- helpers ----------
def sh(*cmd):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True)
    except FileNotFoundError:
        return ""
    return r.stdout.rstrip() if r.returncode == 0 else ""


def now():
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def norm_id(s):
    """TC-1-01, tc_1_01, Tc-1-01 all become TC_1_01."""
    return re.sub(r"[-_]", "_", s.upper())


def id_in(case_id, text):
    """True if case_id appears in text in any separator/case form, as a whole token."""
    n = norm_id(case_id)
    t = re.sub(r"[-_]", "_", text.upper())
    return re.search(r"(?<![A-Z0-9])" + re.escape(n) + r"(?![0-9])", t) is not None


def load(ws):
    p = os.path.join(ws, "state.json")
    if not os.path.exists(p):
        sys.exit(f"no state.json in {ws}")
    return json.load(open(p, encoding="utf-8"))


def save(ws, st):
    json.dump(st, open(os.path.join(ws, "state.json"), "w", encoding="utf-8"), indent=2)


def log(ws, kind, msg):
    with open(os.path.join(ws, "decisions.md"), "a", encoding="utf-8") as f:
        f.write(f"- {now()} | {kind.upper()} | {msg}\n")


def profile():
    if not os.path.exists(PROFILE):
        return {}
    text = open(PROFILE, encoding="utf-8").read()
    m = re.search(r"```json\s*\n(.*?)\n```", text, re.S)
    if not m:
        return {}
    try:
        return json.loads(m.group(1))
    except ValueError as e:
        sys.exit(f"PROJECT-PROFILE.md JSON block is invalid: {e}")


def phase(st, n):
    for p in st["phases"]:
        if int(p["n"]) == int(n):
            return p
    p = {"n": int(n), "title": "", "status": "planned", "base": None, "commit": None, "fix_rounds": 0, "accepted": []}
    st["phases"].append(p)
    return p


def changed_files(since=None):
    files = set()
    if since:
        files |= set(filter(None, sh("git", "diff", "--name-only", since).split("\n")))
    for line in sh("git", "status", "--porcelain", "--untracked-files=all").split("\n"):
        if line.strip():
            files.add(line[3:].split(" -> ")[-1].strip('"'))
    return sorted(files)


def outside_root(files, st):
    pre = set(st.get("preexisting_dirty", []))
    return [f for f in files if not f.startswith(ROOT + "/") and f not in pre and not match(f, NOISE)]


def secret_problems(files):
    """Credential files must never be committable."""
    return [f"{f} is not gitignored: add it to .gitignore before anything else (it holds test credentials)"
            for f in files if os.path.basename(f) in SECRET_FILES]


def plan_section(ws, n):
    text = open(os.path.join(ws, "03-plan.md"), encoding="utf-8").read()
    m = re.search(rf"^(#{{2,4}})\s*Phase\s+{n}\b.*?$", text, re.M | re.I)
    if not m:
        sys.exit(f"Phase {n} heading not found in 03-plan.md")
    rest = text[m.end():]
    e = re.search(rf"^#{{2,{len(m.group(1))}}}\s", rest, re.M)
    return rest[: e.start()] if e else rest


def field(section, name):
    m = re.search(rf"\*\*{name}[^*]*\*\*:?(.*?)(?=^\s*[-*]\s+\*\*|\Z)", section, re.S | re.M | re.I)
    return m.group(1) if m else ""


def allowed_globs(ws, n):
    return re.findall(r"`([^`]+)`", field(plan_section(ws, n), "Allowed File Areas"))


def phase_acs(ws, n):
    sec = plan_section(ws, n)
    acs = re.findall(r"\bAC-[A-Za-z0-9]+(?:\.[A-Za-z0-9]+)*", field(sec, "Acceptance Criteria") + field(sec, "REQ"))
    return sorted(set(acs))


def match(path, globs):
    for g in globs:
        g = g.strip()
        if g.endswith("/") and (path.startswith(g) or ("/" + g) in ("/" + path)):
            return True
        if fnmatch.fnmatch(path, g) or fnmatch.fnmatch(path, g.replace("**/", "")):
            return True
    return False


def rows(path):
    if not os.path.exists(path):
        return []
    return rows_text(open(path, encoding="utf-8").read())


def rows_text(text):
    out, head = [], None
    for line in text.split("\n"):
        if not line.strip().startswith("|"):
            head = None
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c):
            continue
        if head is None:
            head = [c.lower() for c in cells]
            continue
        out.append(dict(zip(head, cells)))
    return out


def col(row, *names):
    for k, v in row.items():
        if any(n in k for n in names):
            return v
    return ""


def clean(s):
    return re.sub(r"[*`]", "", s).strip().upper()


def report_rows(ws, n):
    d = os.path.join(ws, "phases", f"phase-{n}")
    res = []
    for name in ("test-report.md", "ui-report.md"):
        for r in rows(os.path.join(d, name)):
            raw = clean(col(r, "test id", "flow id", "case", "id"))
            m = re.match(ID_RE, raw)
            if not m:
                continue
            res.append({"file": name, "id": m.group(0), "ac": col(r, "req", "ac"),
                        "status": clean(col(r, "status", "result")), "evidence": col(r, "evidence", "screenshot", "log")})
    return d, res


# ---------- evidence readers ----------
def junit_cases(path):
    """[(name, classname, status, message)] from a JUnit XML file (pytest, PHPUnit, Jest, Frappe, Vitest...)."""
    out = []
    root = ET.parse(path).getroot()
    for tc in root.iter("testcase"):
        name, cls = tc.get("name", ""), tc.get("classname", "") or tc.get("class", "")
        st, msg = "PASS", ""
        for child in tc:
            tag = child.tag.lower()
            if tag in ("failure", "error"):
                st, msg = "FAIL", (child.get("message") or child.text or "")[:200]
            elif tag == "skipped":
                st, msg = "SKIPPED", (child.get("message") or "")[:200]
        out.append((name, cls, st, msg))
    return out


def confirm_junit(full, cid, st):
    try:
        cases = [c for c in junit_cases(full) if id_in(cid, c[0] + " " + c[1])]
    except ET.ParseError as e:
        return False, f"invalid JUnit XML: {e}"
    if not cases:
        return False, "no <testcase> whose name contains the case id"
    got = {c[2] for c in cases}
    if got == {st}:
        return True, ""
    return False, f"JUnit says {sorted(got)} for {len(cases)} matching testcase(s), report says {st}"


def confirm_line(text, cid, st):
    up = text.upper()
    if not id_in(cid, text):
        return False
    words = PASS_WORDS if st == "PASS" else FAIL_WORDS
    has = re.search(rf"(?<![A-Z]){words}(?![A-Z])", up) is not None
    other = re.search(rf"(?<![A-Z]){FAIL_WORDS if st == 'PASS' else PASS_WORDS}(?![A-Z])", up) is not None
    return has and not (st == "PASS" and other)


def gate_evidence(ws, n, quiet=False):
    d, rs = report_rows(ws, n)
    errs = []
    if not rs:
        errs.append("no test case rows (TC-/UI-/API- ids) found in test-report.md / ui-report.md")
    for r in rs:
        st, cid = r["status"], r["id"]
        r["confirmed"] = False
        if st not in STATUSES:
            errs.append(f"{cid}: status '{st}' is not one of {STATUSES}")
            continue
        if st in ("BLOCKED", "NOT RUN"):
            continue
        refs = re.findall(r"((?:shards/[\w.-]+/)?evidence/[^\s`|,)]+)", r["evidence"])
        if not refs:
            errs.append(f"{cid}: {st} without an evidence/ reference")
            continue
        problems = []
        for ref in refs:
            fpath, _, line = ref.partition(":")
            fpath = fpath.split("#")[0]
            full = os.path.join(d, fpath)
            if not os.path.exists(full):
                problems.append(f"evidence file missing: {fpath}")
                continue
            if fpath.endswith(".xml"):
                ok, why = confirm_junit(full, cid, st)
                if ok:
                    r["confirmed"] = True
                else:
                    problems.append(f"{fpath}: {why}")
            elif fpath.endswith(".json"):
                try:
                    j = json.load(open(full, encoding="utf-8"))
                    if clean(j.get("status", "")) == st and norm_id(j.get("id", "")) == norm_id(cid):
                        r["confirmed"] = True
                    else:
                        problems.append(f"{fpath} says {j.get('id')} {j.get('status')}, report says {st}")
                except ValueError:
                    problems.append(f"{fpath} is not valid JSON")
            elif line.isdigit():
                lines = open(full, encoding="utf-8", errors="replace").read().split("\n")
                k = int(line)
                if 1 <= k <= len(lines) and confirm_line(lines[k - 1], cid, st):
                    r["confirmed"] = True
                else:
                    shown = lines[k - 1][:120] if 1 <= k <= len(lines) else "(no such line)"
                    problems.append(f"{fpath}:{k} does not show {st} for {cid}: {shown}")
            elif not fpath.endswith((".png", ".jpg", ".webm", ".html")):
                problems.append(f"{fpath}: cite a line (file.txt:<line>), a JUnit .xml, or a runner .json")
        if not r["confirmed"]:
            errs.append(f"{cid}: not confirmed. " + ("; ".join(problems) or "screenshots alone are not proof"))
    if not quiet:
        print(f"evidence: {len(rs)} rows, {len(errs)} problems")
        for e in errs:
            print("  - " + e)
    return errs, rs


def gate_coverage(ws, n, rs, quiet=False):
    acs = phase_acs(ws, n)
    passed = {a for r in rs if r["status"] == "PASS" and r.get("confirmed")
              for a in re.findall(r"AC-[A-Za-z0-9]+(?:\.[A-Za-z0-9]+)*", r["ac"])}
    miss = [a for a in acs if a not in passed]
    if not quiet:
        print(f"coverage: {len(acs)} ACs in phase {n}, {len(acs) - len(miss)} with an evidence-confirmed PASS row")
        for a in miss:
            print(f"  - {a}: no confirmed PASS row")
        if not acs:
            print("  - phase has no AC ids under **Acceptance Criteria** in 03-plan.md")
    return miss if acs else ["no ACs"]


def gate_bugs(ws, n, quiet=False):
    d = os.path.join(ws, "phases", f"phase-{n}")
    open_bugs = []
    files = [f for f in sorted(os.listdir(d)) if re.match(r"bugs.*\.md$", f)] if os.path.isdir(d) else []
    sd = os.path.join(d, "shards")
    for s in sorted(os.listdir(sd)) if os.path.isdir(sd) else []:
        if os.path.isdir(os.path.join(sd, s)):
            files += [os.path.join("shards", s, f) for f in sorted(os.listdir(os.path.join(sd, s))) if re.match(r"bugs.*\.md$", f)]
    for f in files:
        text = open(os.path.join(d, f), encoding="utf-8").read()
        for m in re.finditer(r"^###\s+(BUG-[\w-]+)(.*?)(?=^###\s+BUG-|\Z)", text, re.S | re.M):
            s = re.search(r"\*?\*?Status\*?\*?:?\s*`?([\w-]+)", m.group(2))
            status = s.group(1).lower() if s else "open"
            if status not in ("verified", "deferred-by-user"):
                open_bugs.append(f"{m.group(1)} ({f}): {status}")
    if not quiet:
        print(f"bugs: {len(open_bugs)} not verified")
        for b in open_bugs:
            print("  - " + b)
    return open_bugs


def gate_scope(ws, n, quiet=False):
    st = load(ws)
    p = phase(st, n)
    prof = profile()
    globs = allowed_globs(ws, n)
    protected = prof.get("protected_paths", [])
    files = outside_root(changed_files(p.get("base")), st)
    impl = os.path.join(ws, "phases", f"phase-{n}", "implementation.md")
    justified = field(open(impl, encoding="utf-8").read(), "Out-of-Scope") if os.path.exists(impl) else ""
    out, just, prot = [], [], []
    for f in files:
        if match(f, protected):
            prot.append(f)
        elif match(f, globs) or match(f, ALWAYS_ALLOWED):
            continue
        elif f in justified:
            just.append(f)
        else:
            out.append(f)
    if not quiet:
        print(f"scope: {len(files)} changed files since {str(p.get('base'))[:10]}, allowed: {globs or 'NONE'}")
        for f in prot:
            print(f"  ! {f} (PROTECTED path from the profile: core/vendor code must not change)")
        for f in just:
            print(f"  ~ {f} (outside scope, justified in implementation.md: tell the user)")
        for f in out:
            print(f"  - {f} (outside scope, not justified)")
    secrets = secret_problems(out)
    out = [f for f in out if os.path.basename(f) not in SECRET_FILES]
    for m in secrets:
        print(f"  ! {m}")
    bad = secrets + prot + out + ([] if globs else ["no Allowed File Areas in plan"])
    return bad, just


# ---------- caches: BRD hash, project context ----------
def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def file_digest(path):
    return sha256_file(path)[:16] if os.path.isfile(path) else "deleted"


def analyst_version():
    """Hash of the analyst's prompt: a changed prompt makes a cached analysis stale."""
    for p in (os.path.join(SKILL_DIR, "..", "..", "agents", "brd-analyst.md"), os.path.join(SKILL_DIR, "SKILL.md")):
        if os.path.isfile(p):
            return sha256_file(p)[:16]
    return "unknown"


def other_states(ws):
    """[(workspace, state)] for every other run in docs/brd-to-production/."""
    out = []
    for d in sorted(os.listdir(ROOT)) if os.path.isdir(ROOT) else []:
        p = os.path.join(ROOT, d)
        if os.path.normpath(p) == os.path.normpath(ws) or not os.path.isfile(os.path.join(p, "state.json")):
            continue
        try:
            out.append((p, json.load(open(os.path.join(p, "state.json"), encoding="utf-8"))))
        except ValueError:
            continue
    return out


def code_changes(since):
    """Changed files outside the workflow folder (committed since `since`, plus the working tree)."""
    return [f for f in changed_files(since) if not f.startswith(ROOT + "/") and not match(f, NOISE)]


def dirty_snapshot():
    return {f: file_digest(f) for f in code_changes(None)}


def tree_fingerprint():
    """Identifies HEAD plus the uncommitted code: changes when any code or test changes."""
    h = hashlib.sha256(sh("git", "rev-parse", "HEAD").encode())
    for f in code_changes("HEAD"):
        h.update(f"{f}:{file_digest(f)}\n".encode())
    return h.hexdigest()[:16]


def cmd_brd_hash(ws, a, opt):
    st = load(ws)
    brd = opt("--brd") or st.get("brd")
    if not brd or not os.path.isfile(brd):
        sys.exit(f"BRD file not found: {brd}")
    cur = {"sha256": sha256_file(brd), "analyst_version": analyst_version()}
    req = os.path.join(ws, "01-requirements.md")
    if "--record" in a:
        if not os.path.isfile(req):
            print("REFUSED: 01-requirements.md does not exist yet; record after the analysis")
            sys.exit(1)
        st["brd_cache"] = dict(cur, path=brd, recorded_at=now())
        save(ws, st)
        log(ws, "brd-hash", f"recorded {cur['sha256'][:12]} (analyst {cur['analyst_version']})")
        print(f"recorded {cur['sha256'][:12]}")
        return

    def same(c):
        return c.get("sha256") == cur["sha256"] and c.get("analyst_version") == cur["analyst_version"]

    own = st.get("brd_cache") or {}
    if own:
        if same(own) and os.path.isfile(req):
            print("MATCH (this workspace): 01-requirements.md is up to date, skip the BRD analysis")
            sys.exit(0)
        if own.get("sha256") != cur["sha256"]:
            print(f"CHANGED: the BRD differs from the analysed version ({own.get('sha256', '')[:12]} -> {cur['sha256'][:12]}). Re-run brd-analyst on the whole BRD.")
            if st.get("approved"):
                print("  The plan is already approved: treat this as a change request. Show the user which REQs changed, re-plan the affected phases, and get approval again.")
        else:
            print("CHANGED: the analyst prompt changed since this BRD was analysed. Re-run brd-analyst.")
        sys.exit(1)
    for other, ost in other_states(ws):
        c = ost.get("brd_cache") or {}
        if same(c) and os.path.isfile(os.path.join(other, "01-requirements.md")):
            print(f"MATCH {other}: copy {other}/01-requirements.md into {ws}/, then run brd-hash {ws} --record.")
            print("  It contains the AMB/CON answers resolved in that run: confirm with the user that they still stand.")
            sys.exit(0)
    print("NEW: no analysed copy of this BRD; run brd-analyst")
    sys.exit(1)


def cmd_context_check(ws, a):
    st = load(ws)
    prof = profile()
    limit = int(prof.get("context_full_refresh_every", 5))
    analysis = os.path.join(ws, "02-project-analysis.md")
    src, c = ws, st.get("context")
    if not c:
        cands = [(o, s["context"]) for o, s in other_states(ws)
                 if s.get("context") and os.path.isfile(os.path.join(o, "02-project-analysis.md"))]
        if cands:
            src, c = max(cands, key=lambda x: x[1].get("recorded_at", ""))
    if "--record" in a:
        if not os.path.isfile(analysis):
            print("REFUSED: 02-project-analysis.md does not exist yet; record after the analysis")
            sys.exit(1)
        full = "--full" in a or not c
        count = 0 if full else int(c.get("incremental_count", 0)) + 1
        st["context"] = {"last_analyzed_commit": sh("git", "rev-parse", "HEAD"), "incremental_count": count,
                         "dirty_at_record": dirty_snapshot(), "recorded_at": now()}
        save(ws, st)
        log(ws, "context", f"{'full' if full else 'incremental'} analysis recorded at {st['context']['last_analyzed_commit'][:10]}")
        print(f"recorded ({'full' if full else f'incremental {count}/{limit}'})")
        return
    if not c:
        print("FULL: no recorded project analysis in any workspace")
        sys.exit(1)
    origin = "" if src == ws else f" (from {src}: copy what is not BRD-specific, re-check the BRD-relevant parts)"
    sha = c.get("last_analyzed_commit") or ""
    if not sha or sh("git", "cat-file", "-t", sha) != "commit":
        print(f"FULL: analysed commit {sha[:10] or '?'} no longer exists (rebase or history rewrite?)")
        sys.exit(1)
    if int(c.get("incremental_count", 0)) >= limit:
        print(f"FULL: {c.get('incremental_count')} incremental refreshes since the last full analysis (limit {limit})")
        sys.exit(1)
    snap = c.get("dirty_at_record") or {}
    files = [f for f in code_changes(sha) if not (f in snap and snap[f] == file_digest(f))]
    deps = [f for f in files if any(fnmatch.fnmatch(os.path.basename(f), g) for g in DEP_FILES)]
    schema = [f for f in files if match(f, SCHEMA_FILES)]
    if (prof.get("stack") or st.get("stack")) in ("frappe", "odoo"):
        print("NOTE: on this stack schema can also live only in the database (UI customisations); check it there too")
    if deps or schema:
        print(f"FULL: dependency or schema files changed since {sha[:10]}: " + ", ".join(deps + schema))
        sys.exit(1)
    if not files:
        print(f"REUSE{origin}: no code change since {sha[:10]}")
        return
    print(f"INCREMENTAL{origin}: {len(files)} files changed since {sha[:10]}; re-analyse only the areas they touch")
    for f in files:
        print("  " + f)


