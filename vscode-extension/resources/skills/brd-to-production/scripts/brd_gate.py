def plan_shards(ws, n):
    """The phase's **Test Shards** table as a list of dicts, or None when the phase declares none."""
    sec = plan_section(ws, n)
    m = re.search(r"\*\*Test Shards\*\*", sec)
    if not m:
        return None
    table = []
    for line in sec[m.end():].split("\n")[1:]:
        if line.strip().startswith("|"):
            table.append(line)
        elif table or re.match(r"\s*[-*]\s+\*\*", line):
            break
    out = []
    for r in rows_text("\n".join(table)):
        tokens = lambda s: [t for t in re.split(r"[,\s]+", clean(s)) if t and t not in ("-", "NONE")]
        out.append({"id": clean(col(r, "id")), "agent": clean(col(r, "agent")).lower(),
                    "acs": re.findall(AC_RE, col(r, "ac")), "deps": tokens(col(r, "depend")),
                    "res": [t.lower() for t in re.split(r"[,\s]+", clean(col(r, "resource"))) if t and t != "-"]})
    return out


def check_shards(ws, n, shards):
    errs, ids = [], [s["id"] for s in shards]
    if not shards:
        errs.append("**Test Shards** has no rows")
    for s in shards:
        if not s["id"] or ids.count(s["id"]) > 1:
            errs.append(f"shard id '{s['id']}' is empty or duplicated")
        if s["agent"] not in SHARD_AGENTS:
            errs.append(f"{s['id']}: agent '{s['agent']}' must be one of {SHARD_AGENTS}")
        for d in s["deps"]:
            if d not in ids or d == s["id"]:
                errs.append(f"{s['id']}: depends on unknown shard '{d}'")
        for r in s["res"]:
            if not re.fullmatch(SHARD_RES_RE, r):
                errs.append(f"{s['id']}: resource '{r}' is not one of none, db:read, db:write, server, fixtures:<name>")
        if not s["acs"]:
            errs.append(f"{s['id']}: no AC ids")
    owner = {}
    for s in shards:
        for ac in s["acs"]:
            owner.setdefault(ac, []).append(s["id"])
    acs = phase_acs(ws, n)
    for ac in acs:
        if len(owner.get(ac, [])) != 1:
            errs.append(f"{ac}: must belong to exactly one shard, found {owner.get(ac) or 'none'}")
    for ac in owner:
        if ac not in acs:
            errs.append(f"{ac}: in a shard but not in the phase's Acceptance Criteria")
    return errs


def shards_conflict(s1, s2, per_shard_db):
    r1, r2 = set(s1["res"]), set(s2["res"])
    if {r for r in r1 & r2 if r.startswith("fixtures:")}:
        return True
    w1, w2 = "db:write" in r1, "db:write" in r2
    if not (w1 or w2):
        return False
    uses1, uses2 = w1 or "db:read" in r1, w2 or "db:read" in r2
    if not (uses1 and uses2):
        return False
    # a separate DB per shard only isolates shards that do not go through the shared app server
    return not per_shard_db or "server" in r1 or "server" in r2


def shard_waves(shards, max_agents, per_shard_db):
    done, waves, left = set(), [], list(shards)
    while left:
        wave = []
        for s in left:
            if len(wave) < max_agents and all(d in done for d in s["deps"]) and \
                    not any(shards_conflict(s, w, per_shard_db) for w in wave):
                wave.append(s)
        if not wave:
            return waves, [s["id"] for s in left]
        waves.append(wave)
        done |= {s["id"] for s in wave}
        left = [s for s in left if s not in wave]
    return waves, []


def cmd_shards(ws, n, opt):
    shards = plan_shards(ws, n)
    acs = phase_acs(ws, n)
    if shards is None:
        print(f"NO SHARDS: phase {n} declares no **Test Shards**; start one brd-test-engineer and one brd-ui-tester as usual")
        if len(acs) > SHARD_HINT_ACS:
            print(f"  hint: the phase has {len(acs)} ACs; a **Test Shards** table would let more testers run in parallel")
        return
    prof = profile()
    max_agents = max(1, int(prof.get("max_test_agents", 4)))
    per_db = bool(prof.get("test_db_per_shard", False))
    errs = check_shards(ws, n, shards)
    waves, cyclic = shard_waves(shards, max_agents, per_db) if not errs else ([], [])
    if cyclic:
        errs.append("dependency cycle between shards: " + ", ".join(cyclic))
    print(f"shards: phase {n}, {len(shards)} shards, max_test_agents={max_agents}, test_db_per_shard={str(per_db).lower()}")
    for s in shards:
        print(f"  {s['id']:5s} {s['agent']:18s} {', '.join(s['acs']) or '-'}  deps: {', '.join(s['deps']) or '-'}  res: {', '.join(s['res']) or 'none'}")
    if errs:
        for e in errs:
            print("  - " + e)
        print("RESULT: FAIL - fix the **Test Shards** table in 03-plan.md")
        sys.exit(1)
    if len(acs) <= SHARD_HINT_ACS:
        print(f"  note: only {len(acs)} ACs; each shard re-reads the phase, so two testers may be faster here")
    ids = {s["id"] for s in shards}
    state = {k: [x.strip().upper() for x in (opt(f"--{k}") or "").split(",") if x.strip()] for k in ("done", "running", "failed")}
    unknown = [x for v in state.values() for x in v if x not in ids]
    if unknown:
        sys.exit(f"unknown shard ids: {', '.join(unknown)}")
    if not any(state.values()) and opt("--done") is None:
        for i, w in enumerate(waves, 1):
            print(f"WAVE {i}: " + " ".join(s["id"] for s in w))
        print(f"REGRESSION: after the last wave, GATE regression {ws} {n}")
        print(f"Dispatch: start a shard as soon as `shards {ws} {n} --done ... --running ...` lists it as READY; do not wait for a whole wave")
        return
    done, running, failed = set(state["done"]), set(state["running"]), set(state["failed"])
    blocked = set()
    changed = True
    while changed:
        changed = False
        for s in shards:
            if s["id"] not in blocked | failed | done and any(d in failed | blocked for d in s["deps"]):
                blocked.add(s["id"])
                changed = True
    busy = [s for s in shards if s["id"] in running]
    ready, waiting = [], []
    for s in shards:
        if s["id"] in done | running | failed | blocked:
            continue
        why = [f"needs {d}" for d in s["deps"] if d not in done]
        clash = [o["id"] for o in busy + ready if shards_conflict(s, o, per_db)]
        if clash:
            why.append("shares a resource with " + ", ".join(clash))
        if not why and len(busy) + len(ready) >= max_agents:
            why.append(f"max_test_agents={max_agents} reached")
        if why:
            waiting.append((s, why))
        else:
            ready.append(s)
    print("READY: " + (" ".join(s["id"] for s in ready) or "none"))
    for s, why in waiting:
        print(f"WAITING: {s['id']} ({'; '.join(why)})")
    for b in sorted(blocked):
        print(f"BLOCKED: {b} (a dependency failed: run it after the fix loop)")
    if done == ids:
        print(f"ALL DONE: run GATE shard-merge {ws} {n}, then GATE regression {ws} {n}")


def shard_merge(ws, n, quiet=False):
    shards = plan_shards(ws, n)
    if shards is None:
        return [f"phase {n} declares no **Test Shards**"]
    errs = check_shards(ws, n, shards)
    d = os.path.join(ws, "phases", f"phase-{n}")
    out, seen, notes = {"test-report.md": [], "ui-report.md": []}, {}, []
    for s in shards:
        rp = os.path.join(d, "shards", s["id"], "report.md")
        if not os.path.isfile(rp):
            errs.append(f"{s['id']}: shards/{s['id']}/report.md is missing")
            continue
        count = 0
        for r in rows(rp):
            m = re.match(ID_RE, clean(col(r, "test id", "flow id", "case", "id")))
            if not m:
                continue
            cid = m.group(0)
            if norm_id(cid) in seen:
                errs.append(f"{cid}: in both {seen[norm_id(cid)]} and {s['id']}")
                continue
            seen[norm_id(cid)] = s["id"]
            ac = col(r, "req", "ac")
            stray = [x for x in re.findall(AC_RE, ac) if x not in s["acs"] and not x.startswith("AC-REG")]
            if stray:
                notes.append(f"{cid} ({s['id']}): covers {', '.join(stray)}, owned by another shard")
            ev = re.sub(r"(?<![\w/])evidence/", f"shards/{s['id']}/evidence/", col(r, "evidence", "screenshot", "log"))
            desc = col(r, "scenario", "description", "title", "flow")
            target = "ui-report.md" if s["agent"] == "brd-ui-tester" else "test-report.md"
            out[target].append(f"| {cid} | {s['id']} | {ac} | {desc} | {col(r, 'status', 'result')} | {ev} |")
            count += 1
        if not count:
            errs.append(f"{s['id']}: report.md has no TC-/UI-/API- rows")
    for name, lines in out.items():
        path = os.path.join(d, name)
        if os.path.isfile(path) and GENERATED not in open(path, encoding="utf-8").read():
            if lines:
                errs.append(f"{name} was written by hand: move its rows into a shard report, then delete it")
            continue
        if not lines:
            if os.path.isfile(path):
                os.remove(path)
            continue
        kind = "Browser/API" if name == "ui-report.md" else "Unit & scenario"
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"# {kind} report: phase {n} (merged from shards)\n\n{GENERATED}\n\n"
                    "| Test ID | Shard | AC | Description | Status | Evidence |\n|---|---|---|---|---|---|\n"
                    + "\n".join(lines) + "\n")
    if not quiet:
        print(f"shard-merge: {len(seen)} rows from {len(shards)} shards, {len(errs)} problems")
        for e in errs:
            print("  - " + e)
        for x in notes:
            print("  ~ " + x)
    return errs


# ---------- regression ----------
def run_check(name, cmd, out, junit_required):
    """Run one regression command; a JUnit file at <out>.xml decides PASS/FAIL when present."""
    try:
        code = subprocess.run(cmd, shell=True, timeout=REGRESSION_TIMEOUT).returncode
    except subprocess.TimeoutExpired:
        return {"name": name, "cmd": cmd, "result": "FAIL", "why": f"timed out after {REGRESSION_TIMEOUT}s"}
    res = {"name": name, "cmd": cmd, "exit": code, "result": "PASS" if code == 0 else "FAIL"}
    if code != 0:
        res["why"] = f"exit code {code}"
    xml = out + ".xml"
    if os.path.isfile(xml):
        try:
            cases = junit_cases(xml)
        except ET.ParseError as e:
            return dict(res, result="FAIL", why=f"invalid JUnit XML: {e}")
        res.update(passed=sum(c[2] == "PASS" for c in cases), failed=sum(c[2] == "FAIL" for c in cases),
                   skipped=sum(c[2] == "SKIPPED" for c in cases))
        if res["failed"] or not cases:
            res.update(result="FAIL", why=f"{res['failed']} failing of {len(cases)} JUnit cases")
    elif junit_required and res["result"] == "PASS":
        res.update(result="FAIL", why=f"no JUnit XML at {xml}")
    return res


def cmd_regression(ws, n):
    st = load(ws)
    p = phase(st, n)
    prof = profile()
    cmds = prof.get("commands", {})
    k = int((p.get("regression") or {}).get("k", 0)) + 1
    rel = f"evidence/regression-{k}"
